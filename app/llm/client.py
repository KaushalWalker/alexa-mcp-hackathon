
import os
from typing import Protocol


class LLMClient(Protocol):
    """Common interface for DayPilot language model clients."""

    def generate(self, prompt: str) -> str:
        """Generate a response from a prompt."""
        ...


class MockLLMClient:
    """Local mock client for development without API costs."""

    def generate(self, prompt: str) -> str:
        prompt = prompt.strip()

        if not prompt:
            return "Please tell me what you need help with."

        return (
            "DayPilot AI (mock mode): I received your request: "
            f"{prompt}\n\n"
            "I can connect this request to DayPilot's planning tools "
            "once the AI integration is configured."
        )


class OpenAILLMClient:
    """OpenAI-powered assistant responses."""

    def __init__(self) -> None:
        api_key = os.getenv("OPENAI_API_KEY")

        if not api_key:
            raise ValueError(
                "OPENAI_API_KEY is missing. Configure it in your .env file."
            )

        # Import only when the OpenAI provider is selected.
        from openai import OpenAI

        self.client = OpenAI(api_key=api_key)

    def generate(self, prompt: str) -> str:
        response = self.client.chat.completions.create(
            model=os.getenv("OPENAI_CHAT_MODEL", "gpt-4o-mini"),
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are DayPilot, a practical AI personal planning "
                        "assistant. The application supplies a daily plan "
                        "generated by its scheduling engine. Treat that plan "
                        "as the source of truth. Explain it clearly and "
                        "concisely, prioritize the user's next action, and "
                        "mention unscheduled work when relevant. Never invent "
                        "calendar events, claim to have changed a task, or "
                        "claim to have saved changes that the application "
                        "has not performed."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
            max_completion_tokens=250,
            temperature=0.3,
        )

        content = response.choices[0].message.content

        if not content:
            return "I couldn't generate a response. Please try again."

        return content.strip()


def get_llm_client() -> LLMClient:
    """Select the configured language model provider."""

    provider = os.getenv("LLM_PROVIDER", "mock").strip().lower()

    if provider == "mock":
        return MockLLMClient()

    if provider == "openai":
        return OpenAILLMClient()

    raise ValueError(
        f"Unsupported LLM_PROVIDER: {provider!r}. "
        "Supported providers are 'mock' and 'openai'."
    )
